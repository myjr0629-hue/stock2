// ----------------------------------------------------------------------------
// 왜 필요한가 (2026-09-10 실측)
//
//   대표: 「업데이트하고 실행하니까 상단에 AI 로고가 안 나오네.
//          이것은 업데이트랑 상관없이 웹에서 되는 거 아니야?」 — 맞다. 웹이다.
//   그런데 배포된 HTML·CSS 에는 배지가 분명히 있었다(마크업·금색 #E8C877 확인).
//   결정적 증거: 같은 화면의 「AI 모닝브리핑 · **오후 8:15 ET 생성**」이
//   25분 전 내가 복구한 그 브리핑이었다(generatedAt 00:15:25Z).
//   → **API 는 최신인데 화면(HTML/JS)은 배포 전 판**이었다.
//
//   범인은 서비스워커의 HTML 폴백이다:
//       fetch(request).catch(() => caches.match(request))
//   앱 콜드스타트에서 네트워크가 한 번 삐끗하면 «지난 세션의 HTML»이 나가고,
//   그 뒤로는 기한도 회복 경로도 없이 그 판에 앉는다. 데이터만 새로 들어온다.
//
//   서버 시각·버전을 물어볼 창구가 없으면 앱이 자기가 낡았다는 걸 알 방법이 없다.
//   그래서 이 라우트를 둔다 — 클라이언트가 자기 스탬프와 비교해 스스로 새로고침한다.
// ============================================================================
import { NextResponse } from 'next/server';

export const dynamic = 'force-dynamic';

export async function GET() {
    return NextResponse.json(
        { stamp: process.env.NEXT_PUBLIC_BUILD_STAMP || 'dev' },
        { headers: { 'Cache-Control': 'no-store, no-cache, must-revalidate, max-age=0' } },
    );
}
