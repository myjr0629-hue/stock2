#!/usr/bin/env node
// src/lib/ai/adviceGuard.ts(서빙 권유어 가드) → scripts/lambda-cross-sector/adviceGuard.generated.js
// Lambda 는 TS 를 못 불러 권유어 고침 요청을 건너뛰었다(관문 10241403·1426). 같은 가드를 그대로 옮겨 Lambda 고침 사유 = 서빙 판정이 되게 한다.
// tests/closingReport.test.tsx 가 다시 만들어 파일과 같은지 확인한다(원본만 고치고 재생성을 잊으면 실패).
const fs = require('fs'), path = require('path'), ts = require('typescript');
const root = path.resolve(__dirname, '..');
const SRC = path.join(root, 'src/lib/ai/adviceGuard.ts');
const OUT = path.join(root, 'scripts/lambda-cross-sector/adviceGuard.generated.js');
function build() {
    const js = ts.transpileModule(fs.readFileSync(SRC, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, removeComments: true } }).outputText;
    return `// GENERATED by scripts/build-lambda-advice-guard.cjs from src/lib/ai/adviceGuard.ts — do not edit\n${js}`;
}
module.exports = { build, OUT };
if (require.main === module) { fs.writeFileSync(OUT, build()); console.log('wrote', path.relative(root, OUT)); }
