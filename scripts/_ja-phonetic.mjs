// ⛔ 왜 (대표 지시 2026-08-25)
//   "숫자와 특수 금융 한자는 히라가나/가타카나로 풀어서 전달(Phonetic Conversion)해야
//    발음 사고가 나지 않습니다"
//   실제로 관세 편 대본에 「四.五四%」「〇.八六%」「EWC」 가 그대로 들어가 있었다.
//   한자 숫자에 마침표가 낀 형태는 읽는 법이 정해져 있지 않아 TTS 가 제멋대로 읽는다.
//
// ⛔ 범위를 «좁게» 잡는다 — 퍼센트 앞의 숫자와 영문 약어만 바꾼다.
//   「四日前」(よっか まえ) 같은 말까지 건드리면 오히려 망가진다.
//
// 단독 테스트: node scripts/_ja-phonetic.mjs
// ============================================================================

const KANJI_DIGIT = {
  '〇': 'ゼロ', '零': 'ゼロ', '一': 'イチ', '二': 'ニ', '三': 'サン', '四': 'ヨン',
  '五': 'ゴ', '六': 'ロク', '七': 'ナナ', '八': 'ハチ', '九': 'キュウ',
};

// ⛔ 티커·약어는 «읽는 법» 이 따로 있다. 알파벳 그대로 넘기면 영어 발음이 섞인다.
const ACRONYM = {
  'S&P500': 'エスアンドピー ゴヒャク',
  'FOMC': 'エフオーエムシー', 'NVDA': 'エヌビディア', 'EWC': 'イーダブリューシー',
  'SPY': 'エスピーワイ', 'PCE': 'ピーシーイー', 'ETF': 'イーティーエフ',
  'GDP': 'ジーディーピー', 'CPI': 'シーピーアイ', 'FRB': 'エフアールビー',
  'EWJ': 'イーダブリュージェー', 'EWY': 'イーダブリューワイ',
  'AI': 'エーアイ',
};

/** 「五十」「十五」「四」 같은 한자 정수를 가나로. 십 단위까지만 (그 위는 대본에 안 쓴다) */
export function kanjiIntToKana(s) {
  if (s === '十') return 'ジュウ';
  const m = s.match(/^([〇零一二三四五六七八九])?十([〇零一二三四五六七八九])?$/);
  if (m) {
    const tens = m[1] ? KANJI_DIGIT[m[1]] : '';
    const ones = m[2] ? KANJI_DIGIT[m[2]] : '';
    return `${tens}ジュウ${ones}`;
  }
  return [...s].map((c) => KANJI_DIGIT[c] ?? c).join('');
}

export function jaPhonetic(text) {
  let t = text || '';
  // ① 소수점이 낀 한자 숫자 + % → 「ヨンテンゴヨンパーセント」
  t = t.replace(/([〇零一二三四五六七八九十]+)[.．]([〇零一二三四五六七八九]+)\s*[%％]/g,
    (_, a, b) => `${kanjiIntToKana(a)}テン${[...b].map((c) => KANJI_DIGIT[c] ?? c).join('')}パーセント`);
  // ② 정수 한자 숫자 + %
  t = t.replace(/([〇零一二三四五六七八九十]+)\s*[%％]/g, (_, a) => `${kanjiIntToKana(a)}パーセント`);
  // ③ 아라비아 숫자 + % (소수 포함)
  t = t.replace(/(\d+(?:\.\d+)?)\s*[%％]/g, '$1パーセント');
  // ④ 영문 약어 — 긴 것부터 (S&P500 이 SPY 보다 먼저 걸려야 한다)
  for (const k of Object.keys(ACRONYM).sort((a, b) => b.length - a.length))
    t = t.replace(new RegExp(k.replace(/[&]/g, '\\&'), 'g'), ACRONYM[k]);
  return t;
}

/** 가나가 있으면 일본어로 본다 — 대본에 lang 필드가 없어서 글자로 판별한다 */
export const isJa = (s) => /[ぁ-んァ-ヴ]/.test(s || '');

// ── 단독 실행 시 자체 검증 ──────────────────────────────────────────────────
// ⛔ Windows 는 file:///C:/... 형태라 `file://${argv[1]}` 비교가 «조용히» 빗나간다.
//   실제로 그래서 자체 검증이 아무 출력 없이 통과한 것처럼 보였다. 파일명으로 본다.
if (process.argv[1] && process.argv[1].replace(/\\/g, '/').endsWith('_ja-phonetic.mjs')) {
  const CASES = [
    ['トヨタは四.五四%', 'ヨンテンゴヨンパーセント'],
    ['カナダ本体は〇.八六%', 'ゼロテンハチロクパーセント'],
    ['上位四.二%です', 'ヨンテンニパーセント'],
    ['全品目に五十%です', 'ゴジュウパーセント'],
    ['車は十五%になるはずが', 'ジュウゴパーセント'],
    ['今夜はEWCを見ます', 'イーダブリューシー'],
    ['四日前は引き下げ合意でした', '四日前'],          // ⛔ 바뀌면 안 된다
    ['コアPCEとS&P500', 'エスアンドピー'],
  ];
  let bad = 0;
  for (const [inp, must] of CASES) {
    const out = jaPhonetic(inp);
    const ok = out.includes(must);
    if (!ok) bad++;
    console.log(`${ok ? '✔' : '✗'} ${inp.padEnd(22)} → ${out}`);
  }
  console.log(bad ? `\n⛔ ${bad}건 실패` : '\n전부 통과');
  process.exit(bad ? 1 : 0);
}
